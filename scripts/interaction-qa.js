// Run after observing the home-page snapshot: npx playwright-cli run-code --filename=scripts/interaction-qa.js
async (page) => {
  const failures = []
  page.on('pageerror', error => failures.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://127.0.0.1:4173/')
  await page.keyboard.press('Tab')
  if (await page.locator(':focus').textContent() !== 'Skip to content') throw new Error('Skip link is not first in keyboard order')
  await page.keyboard.press('Enter')
  if (await page.locator(':focus').getAttribute('id') !== 'main') throw new Error('Skip link did not focus main')
  const menu = page.locator('summary').filter({ hasText: 'Menu' })
  await menu.focus()
  await page.keyboard.press('Enter')
  if (!await page.getByRole('navigation', { name: 'Mobile navigation' }).isVisible()) throw new Error('Menu did not open')
  await page.keyboard.press('Escape')
  if (await page.getByRole('navigation', { name: 'Mobile navigation' }).isVisible()) throw new Error('Escape did not close menu')
  if (await page.locator(':focus').textContent() !== 'Menu') throw new Error('Menu focus was lost')
  await menu.click()
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Projects', exact: true }).click()
  await page.waitForURL('**/projects')
  await page.goBack()
  await page.waitForURL(url => url.pathname === '/')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download resume', exact: true }).click()
  const download = await downloadEvent
  if (download.suggestedFilename() !== 'Joshua-Salvacion-Resume.pdf') throw new Error('Wrong resume download')
  await page.goto('http://127.0.0.1:4173/contact')
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'http://127.0.0.1:4173' })
  await page.getByRole('button', { name: 'Copy email', exact: true }).click()
  await page.getByRole('button', { name: 'Copied', exact: true }).waitFor()
  const clipboard = await page.evaluate(() => navigator.clipboard.readText())
  if (clipboard !== 'salvacion.jsh@gmail.com') throw new Error('Wrong copied email')
  const email = await page.getByRole('link', { name: 'Send email', exact: true }).getAttribute('href')
  if (email !== 'mailto:salvacion.jsh@gmail.com') throw new Error('Wrong email target')
  await page.reload()
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(new Error('denied')) } }))
  await page.getByRole('button', { name: 'Copy email', exact: true }).click()
  if (!(await page.getByRole('status').textContent()).includes('Copy is unavailable')) throw new Error('No copy-error fallback')
  await page.goto('http://127.0.0.1:4173/projects/pcosina')
  await page.getByRole('navigation', { name: 'Case study contents' }).getByRole('link', { name: '04 System architecture' }).click()
  if (!page.url().endsWith('#architecture')) throw new Error('Contents link failed')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const transition = await page.locator('.back-link').evaluate(el => getComputedStyle(el).transitionDuration)
  if (transition !== '0s') throw new Error('Reduced motion not respected')
  if (failures.length) throw new Error(failures.join('\n'))
  return { passed: ['skip-link focus', 'keyboard menu open', 'Escape and focus return', 'mobile navigation', 'browser back', 'PDF download', 'copy email', 'copy failure fallback', 'mailto destination', 'case-study anchor', 'reduced motion'], browserErrors: failures }
}
